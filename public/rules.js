// Описи полів, складностей і гравців + тексти правил (для головної і для вікна «?» у грі).
window.Rules = (() => {
  const SYMBOLS = ['✕', '◯', '△', '□'];
  const COLOR_NAMES = ['синій', 'рожевий', 'бурштиновий', 'фіолетовий'];

  // Узгоджено з server/boards.js
  const BOARDS = {
    classic: {
      size: 3, win: 3, scoring: 'line', maxPlayers: 2,
      title: 'Класика', sub: '3×3 · 3 в ряд',
      short: 'Збери 3 в ряд. Тільки вдвох.',
      sample: [0, 4, 8],
    },
    five: {
      size: 5, win: 4, scoring: 'line', maxPlayers: 4,
      title: 'Велике поле', sub: '5×5 · 4 в ряд',
      short: 'Збери 4 в ряд. Більше місця, щоб обійти блок.',
      sample: [5, 6, 7, 8],
    },
    six: {
      size: 6, win: 4, scoring: 'line', maxPlayers: 4,
      title: 'Арена', sub: '6×6 · 4 в ряд',
      short: 'Збери 4 в ряд на найбільшому полі.',
      sample: [7, 14, 21, 28],
    },
    lines: {
      size: 6, win: 3, scoring: 'points', maxPlayers: 4,
      title: 'Збір ліній', sub: '6×6 · очки за трійки',
      short: 'Гра до кінця поля. Кожна трійка в ряд — очко.',
      sample: [12, 13, 14, 15],
    },
  };

  const MODES = {
    easy: {
      label: 'Легкий', dot: 'easy',
      short: 'Топ-клуби й зірки, багато варіантів',
      rule: '15 топ-клубів, 9 топових збірних, топ-5 ліг (грав в АПЛ, Серії А, Ла Лізі, Бундеслізі, Лізі 1), Кубок світу, Ліга чемпіонів, Євро, Золотий м\'яч і позиції. У кожній клітинці щонайменше 10 правильних відповідей.',
    },
    normal: {
      label: 'Звичайний', dot: 'normal',
      short: 'Плюс Україна, чемпіони ліг, рекорди',
      rule: 'Додаються Динамо, Шахтар, Лаціо, Парма, Ньюкасл, Астон Вілла, збірна України, чемпіони АПЛ, Італії, Іспанії й Німеччини, 300+ голів, 50+ голів і 100+ матчів за збірну. У кожній клітинці щонайменше 6 відповідей.',
    },
    fan: {
      label: 'Фанат', dot: 'fan',
      short: 'Тренери, академії, бомбардири, трансфери',
      rule: 'Усе зі звичайного, плюс «грав у тренера» (Гвардіола, Фергюсон, Моурінью, Зідан, Клопп, Анчелотті, Венгер, Луїс Енріке, Лобановський), вихованці академій (Барселона, Реал, Аякс, МЮ, Динамо, Бенфіка, Спортінг, Ліон, Баварія), кращі бомбардири АПЛ, Серії А, Ла Ліги, Бундесліги й Ліги 1, Golden Boy (кращий молодий гравець Європи), трансфер за 100+ млн, ліги МЛС, Китаю й ОАЕ. У кожній клітинці щонайменше 4 відповіді.',
    },
    mix: {
      label: 'Мікс', dot: 'mix',
      short: 'Усі 95 категорій разом',
      rule: 'Усі категорії гри разом — від Реала й Кубка світу до академії Ліона й Про-ліги ОАЕ — без обмежень на «очевидні» відповіді. Режим для максимальної різноманітності. У кожній клітинці щонайменше 4 відповіді.',
    },
    hard: {
      label: 'Складний', dot: 'hard',
      short: 'Нешаблонні клуби, мало очевидних відповідей',
      rule: 'Додаються Аякс, Порту, Бенфіка, Севілья, Валенсія, Наполі, Рома, Металіст, Дніпро, Бельгія, Хорватія, Уругвай, Кубок Америки, Ліга Європи, Золота бутса і 100+ передач. Більшість категорій нешаблонні, у клітинці 3–15 відповідей і майже немає очевидних зірок.',
    },
  };

  function winRule(b) {
    if (b.scoring === 'points') {
      return `Гра триває, доки на полі є вільні клітинки, які ще можна заповнити. Кожні ${b.win} твої клітинки поспіль — по горизонталі, вертикалі чи діагоналі — дають 1 очко. Лінії можуть перетинатися: 4 поспіль — це 2 очки, 5 поспіль — 3. Перемагає той, у кого більше очок.`;
    }
    return `Перемагає той, хто першим займе ${b.win} клітинки поспіль — по горизонталі, вертикалі чи діагоналі.`;
  }

  const COMMON = [
    'Над стовпцями й біля рядків — клуби, збірні, трофеї, рекорди або позиції.',
    'У свій хід обери клітинку й напиши футболіста, який підходить під <b>обидві</b> умови — рядка і стовпця.',
    'Правильно — клітинка твоя. Помилився — хід переходить далі, а гра покаже, яку умову не виконано.',
    'Не встиг за відведений час — хід переходить далі.',
    'Кожного футболіста можна використати лише <b>один раз</b> за гру. Повтор не зараховується, але й хід не втрачається.',
    'Число в порожній клітинці — скільки гравців з бази ще можна туди поставити. Коли підходящого гравця ставлять в іншу клітинку, число зменшується.',
    'Після гри відповіді на незайняті клітинки не показуються — щоб сітки лишалися цікавими.',
    'Позиції — за основною роллю гравця. Вінгери (Ямаль, Неймар, Сака, Куарежма) рахуються і нападниками, і півзахисниками.',
  ];

  function playersRule(capacity) {
    if (capacity <= 2) return 'Гравці ходять по черзі. Почергово починає то один, то інший.';
    return `Гравці ходять по колу: ${SYMBOLS.slice(0, capacity).join(' → ')}. Кожен має свій колір і символ. Якщо хтось здається або виходить, гра триває без нього, а його клітинки лишаються на полі. Нічия — лише коли погодились усі.`;
  }

  const ACTIONS = [
    '<b>Пропустити хід</b> — якщо не знаєш відповіді.',
    '<b>Нічия</b> — пропозицію бачать інші; вона діє, коли погодились усі. У «Зборі ліній» замість нічиєї — <b>Завершити гру</b>: рахуються очки на цей момент.',
    '<b>Здатися</b> — удвох це перемога суперника, утрьох і вчотирьох — ти вибуваєш із партії.',
    'Якщо хтось втратив з\'єднання (закрив вкладку, пропав інтернет), гра триває. Виключити його можна, лише коли він офлайн щонайменше 2 хвилини <b>і</b> заважає грі — зараз його хід або він пропустив 2 ходи поспіль.',
    '<b>Реванш</b> починається, коли погодились усі. Наступну партію починає наступний гравець.',
  ];

  const li = (arr) => arr.map((x) => `<li>${x}</li>`).join('');

  // Правила конкретної кімнати
  function forRoom({ board, mode, capacity, turnSeconds }) {
    const b = BOARDS[board] || BOARDS.classic;
    const m = MODES[mode] || MODES.normal;
    const timer = turnSeconds ? `${turnSeconds} секунд на хід.` : 'Час на хід не обмежено.';
    return `
      <div class="rules-summary">
        <div><span>Поле</span><b>${b.title}</b><small>${b.sub}</small></div>
        <div><span>Гравців</span><b>${capacity}</b><small>${SYMBOLS.slice(0, capacity).join(' ')}</small></div>
        <div><span>Складність</span><b>${m.label}</b><small>${timer}</small></div>
      </div>
      <h4>Як виграти</h4>
      <p>${winRule(b)}</p>
      <h4>Як ходити</h4>
      <ul>${li(COMMON)}</ul>
      <h4>Гравці</h4>
      <p>${playersRule(capacity)}</p>
      <h4>Категорії · ${m.label}</h4>
      <p>${m.rule}</p>
      <h4>Кнопки</h4>
      <ul>${li(ACTIONS)}</ul>`;
  }

  // Загальні правила на головній
  function overview() {
    const boards = Object.values(BOARDS)
      .map((b) => `<li><b>${b.title} (${b.sub})</b>, ${b.maxPlayers === 2 ? 'вдвох' : '2–4 гравці'}. ${winRule(b)}</li>`)
      .join('');
    const modes = Object.values(MODES).map((m) => `<li><b>${m.label}.</b> ${m.rule}</li>`).join('');
    return `
      <details>
        <summary>Як грати</summary>
        <div class="rules-body">
          <h4>Основне</h4>
          <ul>${li(COMMON)}</ul>
          <h4>Поля</h4>
          <ul>${boards}</ul>
          <h4>Складність</h4>
          <ul>${modes}</ul>
          <h4>Утрьох і вчотирьох</h4>
          <p>${playersRule(4)}</p>
          <h4>Кнопки</h4>
          <ul>${li(ACTIONS)}</ul>
        </div>
      </details>`;
  }

  return { SYMBOLS, COLOR_NAMES, BOARDS, MODES, forRoom, overview, winRule };
})();

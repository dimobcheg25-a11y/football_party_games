// База футболистов.
// p(имя EN, имя RU, имя UA, сборная(ы), клубы, трофеи[, доп. варианты написания])
// Клубы — только те, что используются как категории (см. categories.js),
// засчитываются выступления за основную команду, включая аренды.
// Трофеи: BALLON — Золотой мяч, WC — чемпион мира, UCL — победитель Кубка/Лиги чемпионов, EURO — чемпион Европы,
// COPA — Копа Америка, UEL — Лига Европы / Кубок УЕФА, BOOT — Золотая бутса (европейская),
// G300 — 300+ голов за карьеру (клубы + сборная, официальные матчи), A100 — 100+ голевых передач.
// G300/A100 отмечены только у тех, у кого показатель с запасом выше порога — спорных случаев нет.

function p(name, ru, uk, nat, clubs, awards = '', aliases = '') {
  return {
    name,
    ru,
    uk,
    nations: nat.split(' ').filter(Boolean),
    clubs: clubs.split(' ').filter(Boolean),
    awards: awards.split(' ').filter(Boolean),
    aliases: aliases ? aliases.split('|') : [],
  };
}

